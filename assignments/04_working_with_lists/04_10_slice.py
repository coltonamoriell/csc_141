# Create a list of pizzas
pizzas = ['pepperoni', 'hawaiian', 'veggie', 'margherita', 'bbq chicken', 'meat lovers', 'buffalo']

# Print the first three items
print("The first three items in the list are:")
print(pizzas[:3])

# Print three items from the middle of the list
# (Using indices 2 to 5 to grab three items from the middle)
print("Three items from the middle of the list are:")
print(pizzas[2:5])

# Print the last three items
print("The last three items in the list are:")
print(pizzas[-3:])